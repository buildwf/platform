import { describe, expect, it } from 'vite-plus/test';
import { parseGenArgs } from '../../src/cli/gen-args.ts';
import { generateProcedureTypes } from '../../src/codegen/procedure-types.ts';

describe('generateProcedureTypes', () => {
  it('fills ProcedureMap from every procedure file, named by its prefix', () => {
    const result = generateProcedureTypes(
      [
        { filePath: 'contacts.ts', prefix: 'contacts' },
        { filePath: 'billing/invoices.ts', prefix: 'billing.invoices' },
      ],
      '/project/procedures',
      '/project/.bwf',
    );
    expect(result).toContain('// Auto-generated by void');
    expect(result).toContain('declare module "@buildwf/bwf/rpc"');
    expect(result).toContain('typeof import("../procedures/contacts.ts"), "contacts"');
    expect(result).toContain(
      'typeof import("../procedures/billing/invoices.ts"), "billing.invoices"',
    );
  });

  it('keeps ProcedureMap declared when there are no procedures yet', () => {
    expect(generateProcedureTypes([], '/project/procedures', '/project/.bwf')).toContain(
      'interface ProcedureMap {}',
    );
  });
});

describe('bwf gen procedure', () => {
  it('takes a dotted name: the last word is the export', () => {
    expect(parseGenArgs(['procedure', 'billing.invoices.list'])).toEqual({
      subcommand: 'procedure',
      name: 'billing.invoices.list',
    });
  });

  it.each([[[]], [['contacts']], [['Contacts.get']], [['contacts.get', 'extra']]])(
    'rejects %j',
    (rest) => {
      expect(() => parseGenArgs(['procedure', ...rest])).toThrow(/gen:/);
    },
  );
});

import { relative } from 'pathslash';
import type { ProcedureFile } from '../procedures/scan.ts';

/**
 * Generate .bwf/procedures.d.ts content.
 *
 * Fills `ProcedureMap` in `@buildwf/bwf/rpc` from the types of the files in `procedures/`, so
 * `rpc.contacts.get(input)` is typed from the procedure itself. Only types are imported,
 * so no server code reaches the browser.
 */
export function generateProcedureTypes(
  files: Array<ProcedureFile>,
  proceduresDir: string,
  outDir: string,
): string {
  const lines: Array<string> = [];
  lines.push('// Auto-generated by void — do not edit');
  lines.push('import type { ModuleProcedures } from "@buildwf/bwf/rpc";');
  lines.push('');
  lines.push('declare module "@buildwf/bwf/rpc" {');
  if (files.length === 0) {
    lines.push('  interface ProcedureMap {}');
  } else {
    lines.push('  interface ProcedureMap extends');
    const bases = files.map((file) => {
      const importPath = relative(outDir, `${proceduresDir}/${file.filePath}`);
      return `    ModuleProcedures<typeof import(${JSON.stringify(importPath)}), ${JSON.stringify(file.prefix)}>`;
    });
    lines.push(bases.join(',\n') + ' {}');
  }
  lines.push('}');
  lines.push('');
  return lines.join('\n');
}
